// Composer Phase 2B foundation: editorial note-prominence metadata. Unlike
// SEASON_WEIGHTS_BY_ID above, this map is sparse ON PURPOSE and stays that
// way indefinitely -- there is no synthesizing fallback (contrast
// buildSeasonWeights below), because a missing entry, or a missing note
// key within a present entry, means "no editorial judgment has been made
// yet", not "score this as low/zero". Values are a 1-10 integer scale
// (0 is invalid -- "negligible" is expressed by omitting the key, never by
// scoring it 0), never inferred from top/middle/base/general pyramid
// position, and never required to sum to anything.
//
// Exported (from this source file only -- NOT re-exported through
// index.js/the public package surface, see catalogPackageBoundary.test.js)
// so catalogReferenceIntegrity.test.js can validate it directly. Reading it
// back off the merged `fragrances` array alone would silently swallow a
// typo'd/orphaned fragrance-id key (an unmatched numeric key just never
// gets picked up by the `.map()` below), so the raw map itself must be the
// thing under test for the "every prominence fragrance ID exists" rule.
//
// Composer Phase 2C: first real editorial seed batch (11 fragrances,
// deliberately not optimized for catalog coverage -- chosen for clearly
// recognizable, well-documented signature notes across varied scent
// profiles, including one generalNotes-only fragrance to exercise that
// containment path too). Each fragrance scores only its handful of
// meaningfully perceptible/editorially defining notes, never every
// canonical note in its pyramid.
//
// Editorial rule: a score represents our best estimate of how strongly a
// note contributes to the fragrance's actual PERCEPTUAL identity --
// never assigned from pyramid position, the fragrance's name, or textual
// consensus alone. When confidence is insufficient, the note stays
// unscored rather than guessed.
//   9-10 = defining/signature
//   7-8  = very evident
//   4-6  = clearly perceptible
//   1-3  = secondary but identifiable
//   (absent key) = intentionally unscored
//
// Three clarifications on applying this rule:
// 1. Pyramid position alone neither justifies nor disqualifies a score. A
//    sole top/middle/base note is not automatically prominent just for
//    being alone -- but it should still be scored when perceptual identity
//    genuinely supports it. The caution is against inferring FROM position;
//    it is not a blanket rule against scoring lone notes.
// 2. A prominence score is an independent editorial judgment, not a
//    compositional share -- there is no fixed budget being divided among a
//    fragrance's notes. Overlapping canonical note concepts (e.g. vanilla
//    and bourbonVanilla, or a specific herb alongside a general accord
//    term) may each receive their own score when each independently
//    produces a meaningful Note Explorer result for that exact canonical
//    id. This is not "double-counting": prominence values are never summed
//    or normalized against each other, so two related concepts each being
//    "very evident" simply means both are true, not that credit is split.
// 3. Prominence is fragrance-specific, not note-specific -- the same
//    canonical note may legitimately receive very different scores across
//    related fragrances or flankers, since each judgment is about that
//    note's role in THAT composition's perceptual identity, never about
//    the note as an abstract ingredient. See seaNotes below: Acqua di Gio
//    EDT (id 1) scores it 10 (the fragrance the "aquatic" genre is built
//    on), while Acqua di Gio Elixir (id 306), a documented woodier
//    reinterpretation sharing the same note, scores it only 6 -- neither
//    value was inferred from the other just because the note id matches.
//
// See packages/catalog/tests/noteProminenceSeedBatch.test.js for the
// narrow regression coverage of the Phase 2C batch below,
// noteProminenceSeedBatch2E.test.js for the Phase 2E batch,
// noteProminenceSeedBatch2F.test.js for the Phase 2F batch,
// noteProminenceSeedBatch2G.test.js for the Phase 2G batch,
// noteProminenceSeedBatch2H.test.js for the Phase 2H batch,
// noteProminenceSeedBatch2I.test.js for the Phase 2I batch, and
// noteProminenceSeedBatch2J.test.js for the Phase 2J batch that follows it.
//
